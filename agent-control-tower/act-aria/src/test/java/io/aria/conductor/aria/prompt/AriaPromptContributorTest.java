package io.aria.conductor.aria.prompt;

import io.aria.conductor.common.AriaConstants;
import io.aria.conductor.common.context.ContextAdapter;
import io.aria.conductor.common.context.ContextRequest;
import io.aria.conductor.common.context.ContextSection;
import io.aria.conductor.common.model.Sensitivity;
import org.junit.jupiter.api.Test;

import java.util.List;
import java.util.UUID;

import static org.assertj.core.api.Assertions.assertThat;

/**
 * The Aria managed prompt moved out of the initializer and the chat service into
 * one required context section (spec §8.1 "Policy", P1). The section carries the
 * merged identity/governance/workflow policy; the tool catalog is generated by
 * the tool contributor and must not be duplicated here.
 */
class AriaPromptContributorTest {

    private final AriaPromptContributor contributor = new AriaPromptContributor();

    @Test
    void ariaPolicyContainsWorkflowRulesButNoHardcodedToolCatalog() {
        ContextSection section = contributor.contribute(requestFor(AriaConstants.ARIA_AGENT_ID)).get(0);

        assertThat(section.id()).isEqualTo("policy.aria");
        assertThat(section.content()).contains("instantiate_template");
        assertThat(section.content()).doesNotContain("list_agents:");
        assertThat(section.content()).doesNotContain("decide_approval");
        assertThat(section.content()).doesNotContain("## Available Tools");
    }

    @Test
    void nonAriaAgentGetsNoPolicySection() {
        assertThat(contributor.contribute(requestFor(UUID.randomUUID()))).isEmpty();
    }

    @Test
    void policySectionIsRequiredAndOrdered() {
        ContextRequest request = requestFor(AriaConstants.ARIA_AGENT_ID);

        assertThat(contributor.id()).isEqualTo("policy.aria");
        assertThat(contributor.order()).isEqualTo(20);
        assertThat(contributor.required()).isTrue();
        assertThat(contributor.appliesTo(request)).isTrue();
        assertThat(contributor.appliesTo(requestFor(UUID.randomUUID()))).isFalse();
    }

    @Test
    void preservesTheSddInstantiationGuidanceWordForWord() {
        String content = contributor.contribute(requestFor(AriaConstants.ARIA_AGENT_ID)).get(0).content();

        assertThat(content).contains("Start a governed workflow TEMPLATE by its knowledge item id (templateId)");
        assertThat(content).contains("USE THIS for the spec-driven development loop.");
        assertThat(content).contains("NEVER use create_workflow for the BA->Dev->QA loop; always use instantiate_template.");
        assertThat(content).contains("Always pass issueRepo (owner/repo) and repoUrl parameters");
        assertThat(content).contains("answer trivial questions yourself from the issue body before escalating to the user.");
    }

    @Test
    void mergesTheIdentityGovernanceAndDelegationRules() {
        String content = contributor.contribute(requestFor(AriaConstants.ARIA_AGENT_ID)).get(0).content();

        assertThat(content).contains("You are Aria, the AI operator assistant for the Aria Conductor.");
        assertThat(content).contains("IMPORTANT — knowledge governance:");
        assertThat(content).contains("IMPORTANT — multi-step requests:");
        assertThat(content).contains("IMPORTANT — sequential execution:");
        assertThat(content).contains("IMPORTANT — you are an orchestrator, not a worker:");
        assertThat(content).contains("IMPORTANT — delegation:");
        assertThat(content).contains("IMPORTANT — no guessing:");
        // Operator-only tools are described without listing them (Task 11 replaced
        // "not available" with the honest rule: they exist and the platform refuses them).
        assertThat(content).contains("IMPORTANT — operator-only tools:");
        assertThat(content).contains("the platform refuses your");
    }

    /**
     * Task 11 / F9: the prompt must be honest about the authority boundary it cannot
     * cross. Operator-only tools exist and are refused — not absent — and Aria must not
     * claim it surfaced a decision card it has no tool for. The forbidden tool name stays
     * out of the prompt: the catalog, not the prompt, enumerates tools.
     */
    @Test
    void policyStatesThatOperatorOnlyToolsExistButAreRefused() {
        String content = contributor.contribute(requestFor(AriaConstants.ARIA_AGENT_ID)).get(0).content();

        assertThat(content).contains("IMPORTANT — operator-only tools:");
        assertThat(content).contains("Some tools in your list are operator-only. They exist, but the platform refuses your");
        assertThat(content).contains("never claim a tool is absent when it is only refused");
        assertThat(content).contains("Approval and memory-promotion decisions belong to the operator.");
        assertThat(content).contains("the platform shows the operator's decision card in the");
        assertThat(content).contains("You cannot show that card yourself and you cannot decide it.");
        assertThat(content).contains("an empty match is not an empty catalog");
        assertThat(content).doesNotContain("decide_approval");
        assertThat(content).doesNotContain("## Available Tools");
    }

    private static ContextRequest requestFor(UUID agentId) {
        return new ContextRequest(UUID.randomUUID(), "conv-1", agentId, ContextAdapter.SYNC,
                1, "list my agents", null, Sensitivity.INTERNAL, 24_000, null, "", List.of());
    }
}
